#!/usr/bin/env python3
"""init-harness가 승인받은 설치 설정을 계획·적용한다. 설치·신뢰·전역 설정을 조작하지 않는다."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sys
import tomllib

ROLES = ('researcher', 'test-writer', 'doc-reviewer')
PLUGIN = Path(__file__).resolve().parent.parent
MARKER = '# Generated by superchaeyeons; edits require review.\n'


def generated(body):
    return MARKER + '# content-sha256: ' + hashlib.sha256(body.encode()).hexdigest() + '\n' + body


def unchanged_generated(text):
    if not text.startswith(MARKER):
        return False
    _, header, body = text.split('\n', 2)
    return header == '# content-sha256: ' + hashlib.sha256(body.encode()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', required=True)
    parser.add_argument('--target', choices=('claude', 'codex', 'both'), required=True)
    parser.add_argument('--apply', action='store_true')
    args = parser.parse_args()
    root = Path(args.project).resolve()
    if not root.is_dir():
        parser.error('프로젝트 디렉터리가 존재해야 합니다')
    files, conflicts = [], []

    def safe(rel):
        path = root / rel
        if any(part.is_symlink() for part in [path, *path.parents] if part != root and root in part.parents):
            raise ValueError(rel + ': 심볼릭 링크를 덮어쓰지 않습니다')
        if not path.resolve().is_relative_to(root):
            raise ValueError(rel + ': 프로젝트 밖을 가리키는 경로')
        if path.exists() and not path.is_file():
            raise ValueError(rel + ': 일반 파일이 아님')
        return path

    def put(rel, content, owned=False):
        path = safe(rel)
        old = path.read_text() if path.exists() else None
        if old == content:
            return
        if owned and old is not None and not unchanged_generated(old):
            conflicts.append(rel + ': 기존 사용자 파일과 충돌')
            return
        files.append({'path': rel, 'content': content, 'action': 'create' if old is None else 'update'})

    def skeleton():
        lines = ['# init-harness 실측·승인 뒤 빈칸을 채운다. 공통 설정 원본은 이 파일 한 개다.']
        for line in (PLUGIN / 'scripts/harness-keys.txt').read_text().splitlines():
            if not line or line.startswith('#'):
                continue
            key, kind, name, *_ = line.split('\t')
            if kind in ('slot', 'info'):
                value = '{' + name.strip('{}') + '}'
            elif kind == 'flag':
                value = '0' if key in ('HARNESS_SELF_EDIT', 'POLISH_ENABLED') else '{' + name + '}'
            elif key.startswith(('ASK_', 'BLOCK_')) or key == 'AUTO_ANALYZE':
                value = '1'
            else:
                value = ''
            lines.append(key + '=' + value)
        return '\n'.join(lines) + '\n'

    try:
        for rel, body in (('.claude/harness.conf', skeleton()),
                          ('scripts/dev.conf', (PLUGIN / 'skills/init-harness/references/dev.conf').read_text())):
            if not safe(rel).exists():
                put(rel, body)
        if args.target in ('claude', 'both'):
            rel = '.claude/settings.json'
            path = safe(rel)
            settings = json.loads(path.read_text()) if path.exists() else {}
            if not isinstance(settings, dict):
                raise ValueError('Claude 설정은 JSON 객체여야 합니다')
            settings.setdefault('extraKnownMarketplaces', {}).setdefault('superchaeyeons', {
                'source': {'source': 'github', 'repo': 'chhezue/Superchaeyeons'}, 'autoUpdate': True})
            enabled = settings.setdefault('enabledPlugins', {})
            if enabled.get('superchaeyeons@superchaeyeons', True) is not True:
                raise ValueError('기존 Claude 플러그인 비활성화 값과 충돌')
            enabled['superchaeyeons@superchaeyeons'] = True
            if not path.exists():
                settings['permissions'] = {'deny': ['Read(./.env)', 'Read(./.env.*)', 'Read(**/.env)',
                    'Edit(./.env)', 'Write(./.env)', 'Bash(git push --force:*)', 'Bash(git push -f:*)',
                    'Bash(git reset --hard:*)', 'Bash(git commit --no-verify:*)']}
                bulk = '1'
                config_path = safe('.claude/harness.conf')
                if config_path.exists():
                    for line in config_path.read_text().splitlines():
                        if line.startswith('BLOCK_BULK_DELETE='):
                            bulk = line.split('=', 1)[1]
                if bulk not in ('0', '1'):
                    raise ValueError('BLOCK_BULK_DELETE 값 확인 필요')
                if bulk == '1':
                    settings['permissions']['deny'].append('Bash(rm -rf:*)')
            put(rel, json.dumps(settings, ensure_ascii=False, indent=2) + '\n')
        if args.target in ('codex', 'both'):
            rel = '.codex/config.toml'
            path = safe(rel)
            text = path.read_text() if path.exists() else ''
            parsed = tomllib.loads(text)
            tables = [('marketplaces', 'superchaeyeons', {'source_type': 'git',
                       'source': 'https://github.com/chhezue/Superchaeyeons.git', 'ref': 'main'}),
                      ('plugins', 'superchaeyeons@superchaeyeons', {'enabled': True})]
            for category, name, values in tables:
                existing = parsed.get(category, {}).get(name)
                if existing is not None:
                    if not isinstance(existing, dict) or any(type(existing.get(k)) is not type(v) or existing.get(k) != v for k, v in values.items()):
                        raise ValueError('기존 Codex ' + category + '.' + name + ' 설정과 충돌')
                    continue
                text += '\n[' + category + '.' + json.dumps(name) + ']\n'
                for key, value in values.items():
                    text += key + ' = ' + json.dumps(value, ensure_ascii=False) + '\n'
            tomllib.loads(text)
            put(rel, text)
            runtime = (PLUGIN / 'codex/INSTRUCTIONS.md').read_text().replace('__PLUGIN_ROOT__', str(PLUGIN))
            for role in ROLES:
                source = (PLUGIN / 'agents' / (role + '.md')).read_text()
                if not source.startswith('---\n'):
                    raise ValueError('공통 역할 머리글 없음: ' + role)
                front, separator, body = source[4:].partition('\n---\n')
                if not separator:
                    raise ValueError('공통 역할 본문 없음: ' + role)
                description = next(l[len('description:'):].strip() for l in front.splitlines()
                                   if l.startswith('description:'))
                content = 'name = ' + json.dumps(role) + '\n'
                content += 'description = ' + json.dumps(description, ensure_ascii=False) + '\n'
                content += 'developer_instructions = ' + json.dumps(runtime + '\n\n' + body.strip(), ensure_ascii=False) + '\n'
                if role == 'test-writer':
                    content += '\n[features]\nshell_tool = false\n'
                tomllib.loads(content)
                put('.codex/agents/' + role + '.toml', generated(content), owned=True)
            rules = '# prompt는 지원하는 권한 경계에서만 적용된다. 일반 편집 승인을 강제하지 않는다.\n'
            for pattern in (['git', 'commit'], ['git', 'push'], ['gh', 'pr', 'create'], ['gh', 'pr', 'merge']):
                rules += 'prefix_rule(pattern=' + json.dumps(pattern) + ', decision="prompt")\n'
            put('.codex/rules/harness.rules', generated(rules), owned=True)
        ignore = safe('.gitignore')
        text = ignore.read_text() if ignore.exists() else ''
        needed = []
        if args.target in ('claude', 'both'):
            needed += ['.claude/corrections/', '.claude/polish/']
        if args.target in ('codex', 'both'):
            needed += ['.codex/harness-state/', '.codex/corrections/', '.codex/polish/']
        additions = [p for p in needed if p not in text.splitlines() and '/' + p not in text.splitlines()]
        if additions:
            put('.gitignore', text + ('' if not text or text.endswith('\n') else '\n') + '\n'.join(additions) + '\n')
    except (ValueError, OSError, KeyError, TypeError, StopIteration) as error:
        conflicts.append(str(error))
    # 모든 충돌을 확인한 뒤 적용한다. 각 파일은 같은 폴더에서 원자적으로 교체한다.
    if args.apply and not conflicts:
        for item in files:
            path = safe(item['path'])
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_name(path.name + '.harness-tmp')
            if tmp.exists() or tmp.is_symlink():
                raise ValueError('임시 파일 충돌: ' + str(tmp))
        for item in files:
            path = safe(item['path'])
            tmp = path.with_name(path.name + '.harness-tmp')
            tmp.write_text(item['content'])
            os.replace(tmp, path)
    print(json.dumps({'files': files, 'conflicts': conflicts, 'applied': bool(args.apply and not conflicts)}, ensure_ascii=False))
    return 1 if conflicts else 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except Exception as error:
        print(json.dumps({'files': [], 'conflicts': [str(error)], 'applied': False}, ensure_ascii=False))
        sys.exit(1)
